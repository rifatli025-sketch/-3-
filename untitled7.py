import cartopy.crs as ccrs
import matplotlib.pyplot as plt
import cartopy.feature as cfeature

# Создаем новый график с указанной проекцией PlateCarree
ax = plt.axes(projection=ccrs.PlateCarree())

# Добавляем стандартное изображение карты мира на график
ax.stock_img()

# Устанавливаем координаты для Нью-Йорка и Ташкента (Узбекистан)
ny_lon, ny_lat = -75, 43
uz_lon, uz_lat = 69.24, 41.31

# Рисуем линию, представляющую маршрут между Нью-Йорком и Узбекистаном
plt.plot([ny_lon, uz_lon], [ny_lat, uz_lat],
         color='blue', linewidth=2, marker='o',
         transform=ccrs.Geodetic(),  # Используем геодезическую проекцию для преобразования координат
         )

# Рисуем пунктирную линию между Нью-Йорком и Узбекистаном
plt.plot([ny_lon, uz_lon], [ny_lat, uz_lat],
         color='gray', linestyle='--',
         transform=ccrs.PlateCarree(),  # Используем проекцию PlateCarree для преобразования координат
         )

# Добавляем подпись "New York" к точке с координатами города New York
plt.text(ny_lon - 3, ny_lat - 12, 'New York',
         horizontalalignment='right',  # Горизонтальное выравнивание текста
         transform=ccrs.Geodetic()  # Используем геодезическую проекцию для преобразования координат
         )

# Добавляем подпись "Uzbekistan" к точке с координатами Узбекистана
plt.text(uz_lon + 3, uz_lat - 12, 'Uzbekistan',
         horizontalalignment='left',  # Горизонтальное выравнивание текста
         transform=ccrs.Geodetic()  # Используем геодезическую проекцию для преобразования координат
         )

